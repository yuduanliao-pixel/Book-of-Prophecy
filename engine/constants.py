def ganzhi_name(index: int) -> str:
    """干支序號（0=甲子…59=癸亥）→ 干支名。"""
    index %= 60
    return TIANGAN[index % 10] + DIZHI[index % 12]


def xunkong(day_index: int):
    """日柱干支序 → (空支1, 空支2)。依旬首推。"""
    xun = (day_index % 60) // 10  # 0=甲子旬 … 5=甲寅旬
    b1 = (10 - 2 * xun) % 12
    b2 = (11 - 2 * xun) % 12
    return DIZHI[b1], DIZHI[b2]


