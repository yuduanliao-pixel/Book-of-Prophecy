def ganzhi_index(ganzhi: str) -> int:
    """干支名 → 干支序號（0=甲子…59=癸亥）。"""
    g, z = TIANGAN.index(ganzhi[0]), DIZHI.index(ganzhi[1])
    for i in range(g, 60, 10):
        if i % 12 == z:
            return i
    raise ValueError(f"無效干支：{ganzhi}")


def nayin(ganzhi: str) -> str:
    """干支 → 納音（如 戊辰 → 大林木）。"""
    return NAYIN[ganzhi_index(ganzhi) // 2]
